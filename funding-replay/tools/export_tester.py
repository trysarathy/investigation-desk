"""Create an offline, synthetic-only tester workspace. Output is also a static website."""
import argparse,json,shutil,sys
from decimal import Decimal
from pathlib import Path
root=Path(__file__).resolve().parents[1];sys.path.insert(0,str(root))
from engine import replay
def export(out):
    out.mkdir(exist_ok=True, parents=True)
    if list(out.iterdir()):raise ValueError("Choose a new or empty output folder.")
    static=root/'app/static'; (out/'states').mkdir()
    for name in ('app.js','app.css'):shutil.copyfile(static/name,out/name)
    (out/'offline.js').write_text("""'use strict';
window.clearlineDemoAPI = async function(path,body){
 const ok=data=>({ok:true,status:200,data});
 if(path==='/api/meta')return ok(window.demoMeta);
 if(path!=='/api/evaluate')throw Error('Samples only');
 const q=JSON.parse(body);
 if(!window.demoMeta.scenarios.some(s=>s.id===q.scenario)||!['friday','monday','retro'].includes(q.decision_time)||!['0','8'].includes(q.funding_rate_pct))throw Error('Unavailable sample');
 return new Promise((resolve,reject)=>{
   const script=document.createElement('script');
   script.deliver=data=>resolve(ok(data));
   script.onload=()=>script.remove();script.onerror=()=>{script.remove();reject(Error('Extract the entire ZIP before opening.'));};
   script.src='states/'+q.scenario+'-'+q.decision_time+'-'+q.funding_rate_pct+'.js';
   document.head.append(script);
 });
};
""",encoding='utf8')
    meta={'label':replay.LABEL,'scenarios':[replay.scenario_meta(s) for s in replay.SCENARIOS.values()],'decision_times':replay.decision_times_json(),'default_rate_pct':'8','current_dataset':'sample'}
    (out/'meta.js').write_text('window.demoMeta='+json.dumps(meta,ensure_ascii=True)+';\n',encoding='utf8')
    for sid,s in replay.SCENARIOS.items():
        for dt in ('friday','monday','retro'):
            for rate in ('0','8'):
                v=replay.evaluate(s['events'],dt,Decimal(rate),s)
                (out/'states'/f'{sid}-{dt}-{rate}.js').write_text('document.currentScript.deliver('+json.dumps(v,ensure_ascii=True,separators=(',',':'))+');',encoding='utf8')
    page=(static/'index.html').read_text().replace('/static/app.css','app.css').replace('<script src="/static/app.js"></script>','<script src="meta.js"></script><script src="offline.js"></script><script src="app.js"></script>')
    page=page.replace('<div class="rate-row">','<div class="rate-row">').replace('<span class="rate-input-wrap">','<span class="rate-input-wrap" hidden>').replace('id="rate" name','disabled id="rate" name').replace('id="open-data"','hidden id="open-data"').replace('<section class="panel data-panel"','<section hidden class="panel data-panel"')
    page=page.replace('Reconstructed engine · synthetic fixtures · local only','Tester edition · fixed synthetic results generated by the engine · no uploads, accounts or analytics')
    page=page.replace('<title>Clearline | Funding desk</title>','<title>Clearline | Funding desk (synthetic tester edition)</title>')
    import re
    page=re.sub(r'\s*<section hidden class="panel data-panel".*?</section>','',page,flags=re.S)  # no CSV upload in the shared build
    page=re.sub(r'<button type="button" class="btn btn-quiet" hidden id="open-data"[^>]*>Data</button>','',page)
    assert 'csv-file' not in page and 'open-data' not in page, 'tester build must not contain the Data panel'
    page=page.replace('<footer class="footer">','<aside class="tester-note"><b>Testing this desk</b><p>Choose a checkpoint, read the decision, then inspect the evidence. What would you need before acting on the result? Send that feedback to the person who shared this file.</p><small>Fixed synthetic cases · 0% and 8% rate presets · no uploads or analytics</small></aside><footer class="footer">')
    (out/'index.html').write_text(page,encoding='utf8')
    (out/'START-HERE.txt').write_text('Clearline / Funding desk\n\nExtract the whole folder, then double-click index.html in a desktop browser. No Python, account, network access or bank data is needed. Keep the assets and states folder next to index.html.\n\nTry Friday, retrospective, then return to Friday. Try Forecast customer receipt at Monday, and Friday-afternoon balance at Monday. Which evidence would change your decision? Send your answer directly to the founder; this demo collects nothing.\n',encoding='utf8')
if __name__=='__main__':
    p=argparse.ArgumentParser();p.add_argument('output',type=Path);export(p.parse_args().output)
