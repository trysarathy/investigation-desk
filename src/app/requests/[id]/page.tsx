export const dynamic = "force-dynamic";

function SourceTag({ o }: { o: Observation }) {
  return o.source === "simulated"
    ? <span className="badge" title="Generated by the demo's simulated provider. Not a blockchain observation.">Simulated</span>
    : <span className="badge" title="Read from Ethereum by a live lookup.">Live · Ethereum</span>;
}

function TxRef({ o }: { o: Observation }) {
  return o.source === "live"
    ? <a className="mono" href={explorerTxUrl("ethereum", o.hash)} target="_blank" rel="noreferrer">{shortHash(o.hash)} ↗</a>
    : <span className="mono" title="Simulated transaction: there is no public record to link to.">{shortHash(o.hash)} <span className="faint">(no public record)</span></span>;
}

function evidenceSource(e: Evidence, o: Observation) {
  const s = e.source;
  if (s.kind === "explorer") return o.source === "live" ? <a href={s.url} target="_blank" rel="noreferrer">Explorer ↗</a> : <span className="faint">Simulated event</span>;
  if (s.kind === "settings") return <span className="faint">Request settings</span>;
  if (s.kind === "addresses") return <span className="faint">Request address</span>;
  return null;
}

function TransferRow({ o, r }: { o: Observation; r: PaymentRequest }) {
  const last = o.checks.at(-1);
  const problem = o.attribution.kind === "request" ? transferProblem(o, r) : undefined;
  const official = o.tokenContract === r.tokenContract;
  return (
    <div className="transfer">
      <div style={{ display: "flex", gap: 8, alignItems: "center", flexWrap: "wrap" }}>
        <strong className="amount">{formatUsdc(o.amount)} {o.tokenSymbol}</strong>
        <SourceTag o={o} />
        {official ? <Status status="pass" label="Circle's USDC contract" /> : <Status status="fail" label="Not Circle's USDC contract" />}
      </div>
      <div style={{ textAlign: "right" }}>
        {o.status === "failed" ? <Status status="fail" label="Failed" />
          : o.blockNumber === undefined ? <span className="muted">Not yet in a block</span>
          : <span className="muted">{Math.min(o.confirmations, CONFIRMATIONS)} of {CONFIRMATIONS} confirmations</span>}
      </div>
      <div className="muted" style={{ fontSize: 12 }}>
        <TxRef o={o} /> · from <span className="mono">{o.from.slice(0, 8)}…{o.from.slice(-4)}</span>
        {o.blockNumber !== undefined && <> · block {o.blockNumber.toLocaleString("en-US")}</>}
        {o.tokenContract !== r.tokenContract && <> · contract <span className="mono">{o.tokenContract.slice(0, 8)}…{o.tokenContract.slice(-4)}</span></>}
      </div>
      <div style={{ textAlign: "right", fontSize: 12 }}>{last?.code ? <span><span className="code">{last.code}</span> {last.label}{last.confidence ? ` · ${last.confidence}` : ""}</span> : <span className="faint">{last?.label}</span>}</div>
      <div className="muted" style={{ fontSize: 12, gridColumn: "1 / -1" }}>
        {o.attribution.kind === "request" ? <>Matched: {o.attribution.reason}</> : o.attribution.kind === "ambiguous" ? <>Not matched: {o.attribution.reason}</> : o.attribution.reason}
        {problem && <div className="s-warn" style={{ marginTop: 4 }}>Doesn&apos;t count toward the request: {problem}</div>}
      </div>
    </div>
  );
}

export default async function RequestDetail({ params, searchParams }: { params: Promise<{ id: string }>; searchParams: Promise<{ created?: string }> }) {
  const { id } = await params;
  const { created } = await searchParams;
  const data = await requestsStore().load();
  const r = data.requests[id];
  if (!r) notFound();
  const v = deriveRequest(data, r, CONFIRMATIONS);
  const next = nextAction(v);
  const reply = replyDraft(v);
  const allowed = allowedDecisions(v);
  const transfers = [...v.flagged.map((f) => f.obs), ...v.counted, ...v.ambiguous]
    .filter((o, i, a) => a.findIndex((x) => x.key === o.key) === i)
    .sort((a, b) => (a.firstSeenAt < b.firstSeenAt ? -1 : 1));
  const dismissedObs = Object.values(data.observations).filter((o) => o.attribution.kind === "request" && o.attribution.requestId === r.id && !transfers.includes(o));
  const focus = v.flagged.at(-1)?.obs ?? v.ambiguous.at(-1) ?? v.counted.at(-1);
  const focusCheck = focus?.checks.findLast((c) => c.evidence.length > 0);
  const h = await headers();
  const origin = `${h.get("x-forwarded-proto") ?? "http"}://${h.get("host") ?? "localhost:3000"}`;
  const link = `${origin}/pay/${r.publicId}`;
  const instructions = `Please pay ${formatUsdc(r.amount)} USDC for ${r.invoiceRef}.\nNetwork: Ethereum (USDC only; other tokens or networks will not arrive).\nTo: ${r.receivingAddress}\nUSDC contract: ${r.tokenContract}\nPayment page with live status: ${link}`;
  const demo = demoStatus(data);
  const over = v.outstanding.startsWith("-");
  const label = (o: Observation) => `${formatUsdc(o.amount)} ${o.tokenSymbol} · ${shortHash(o.hash)}`;
  const tone = v.state === "needs_review" ? " attention" : v.state === "matched" ? " go" : "";

  return (
    <div className="page">
      {!["completed"].includes(v.state) && <AutoRefresh ms={4000} />}
      <div className="page-head">
        <div style={{ display: "flex", flexDirection: "column", gap: 4 }}>
          <div className="faint" style={{ fontSize: 12 }}><Link href="/requests">Payment requests</Link> / <span className="mono">{r.id}</span></div>
          <div style={{ display: "flex", alignItems: "center", gap: 12, flexWrap: "wrap" }}>
            <h1 style={{ margin: 0 }}>{r.customerRef} <span className="faint" style={{ fontWeight: 400 }}>{r.invoiceRef}</span></h1>
            <StatePill state={v.state} />
            {r.demo && <span className="demo-flag">Demo · synthetic business data</span>}
          </div>
        </div>
        <div style={{ display: "flex", gap: 8 }}>
          <a className="btn" href={`/pay/${r.publicId}`} target="_blank" rel="noreferrer">Sender page ↗</a>
        </div>
      </div>

      {created && (
        <div className="bar bar-info" role="status" style={{ flexWrap: "wrap" }}>
          Request created. Send the customer this link: <span className="mono" style={{ wordBreak: "break-all" }}>{link}</span>
          <CopyButton text={link} label="Copy link" />
        </div>
      )}

      <div className="cols">
        <div style={{ display: "flex", flexDirection: "column", gap: 16, minWidth: 0 }}>
          <section className={`next${tone}`} aria-label="Next action">
            <div className="faint" style={{ fontSize: 12, textTransform: "uppercase", letterSpacing: "0.04em" }}>Next action</div>
            <h2>{next.title}</h2>
            <div className="muted">{next.detail}</div>
            <div className="who">{next.owner === "No one" || next.owner === "Customer" ? `Waiting on: ${next.owner === "Customer" ? "the customer" : "nobody"}` : r.owner ? `Owner: ${r.owner}` : `Owner: unassigned (usually ${next.owner})`}</div>
            {allowed.length > 0 && (
              <DecisionPanel requestId={r.id} allowed={allowed}
                flagged={v.flagged.map((f) => ({ key: f.obs.key, label: label(f.obs) }))}
                ambiguous={v.ambiguous.map((o) => ({ key: o.key, label: label(o) }))} />
            )}
          </section>

          <div className="figures" role="group" aria-label="Amounts">
            <div className="figure"><span className="k">Requested</span><span className="v">{formatUsdc(r.amount)} <span className="amount-unit">USDC</span></span></div>
            <div className="figure"><span className="k">Received, confirmed</span><span className="v">{formatUsdc(v.received)}</span></div>
            <div className="figure"><span className="k">Confirming</span><span className="v">{formatUsdc(v.pending)}</span></div>
            <div className="figure"><span className="k">{over ? "Over by" : "Outstanding"}</span><span className={`v${v.review === "short" || over ? " short" : ""}`}>{formatUsdc(v.outstanding.replace(/^-/, ""))}</span></div>
          </div>

          <section className="panel">
            <div className="panel-h"><h2>{{ awaiting_payment: "Why it's awaiting payment", transfer_detected: "What's been seen", confirming: "Why it's confirming", matched: "Why it's matched", needs_review: "Why it needs review", completed: "Why it's completed" }[v.state]}</h2></div>
            <ul className="panel-b" style={{ margin: 0, paddingLeft: 32 }}>
              {v.reasons.map((x, i) => <li key={i}>{x}</li>)}
            </ul>
          </section>

          <section className="panel">
            <div className="panel-h"><h2>Transfers</h2><span className="faint">{transfers.length + dismissedObs.length}</span></div>
            {transfers.length === 0 && dismissedObs.length === 0 && <div className="panel-b muted">No transfer to {r.receivingAddress.slice(0, 8)}…{r.receivingAddress.slice(-4)} yet.</div>}
            {transfers.map((o) => <TransferRow key={o.key} o={o} r={r} />)}
            {dismissedObs.map((o) => (
              <div key={o.key} className="transfer" style={{ opacity: 0.75 }}>
                <div><strong className="amount">{formatUsdc(o.amount)} {o.tokenSymbol}</strong> <SourceTag o={o} /> <span className="badge">Marked not a payment</span></div>
                <div style={{ textAlign: "right", fontSize: 12 }}>{o.checks.at(-1)?.code} {o.checks.at(-1)?.label}</div>
                <div className="muted" style={{ fontSize: 12, gridColumn: "1 / -1" }}><TxRef o={o} /> · kept on file with its evidence</div>
              </div>
            ))}
          </section>

          {focus && focusCheck && (
            <section className="panel">
              <div className="panel-h">
                <h2>Evidence <span className="faint" style={{ fontWeight: 400 }}>· {focus.source === "simulated" ? "simulated transfer" : "live Ethereum data"} {shortHash(focus.hash)}</span></h2>
                <span className="faint" style={{ fontSize: 12 }}>Engine verdict: <span className="code">{focusCheck.code}</span> {focusCheck.label}{focusCheck.confidence ? ` · ${focusCheck.confidence}` : ""}</span>
              </div>
              <ol className="timeline">
                {focusCheck.evidence.map((e) => (
                  <li key={e.id}>
                    <div className="tl-label" style={{ display: "flex", flexDirection: "column", gap: 4 }}><span>{e.label}</span><span className={`status s-${e.status}`} style={{ fontSize: 12 }}><Status status={e.status} /></span></div>
                    <div className="tl-value"><span>{e.value}</span>{e.detail && <span className="tl-detail">{e.detail}</span>}</div>
                    <div className="tl-source">{evidenceSource(e, focus)}</div>
                  </li>
                ))}
              </ol>
              <div className="faint" style={{ padding: "8px 16px", fontSize: 12, borderTop: "1px solid var(--border)" }}>
                Checked {formatTime(focusCheck.at)} with {focusCheck.ruleVersion} and {focusCheck.settingsVersion}. Earlier checks are kept: {focus.checks.length} on file.
              </div>
            </section>
          )}

          <section className="panel">
            <div className="panel-h"><h2>What this can&apos;t tell you</h2></div>
            <ul className="panel-b" style={{ margin: 0, paddingLeft: 32 }}>
              <li>A confirmed transfer shows the USDC reached the address. It doesn&apos;t show the customer was credited: only your acknowledgement does.</li>
              {transfers.some((o) => o.source === "simulated") && <li>Simulated transfers: no blockchain was asked. The issuer&apos;s freeze status and the sender&apos;s history were not checked, and none is shown.</li>}
              {v.ambiguous.length > 0 && <li>The chain can&apos;t say which invoice a transfer was meant for when requests share an address.</li>}
              {transfers.some((o) => o.source === "live") && <li>Live lookups: the sender&apos;s identity is not known from the chain.</li>}
            </ul>
          </section>

          <section className="panel">
            <div className="panel-h"><h2>Activity</h2><span className="faint">kept in full, newest first</span></div>
            <ol className="activity">
              {[...r.activity].reverse().map((a, i) => (
                <li key={i}><span className="faint">{formatTime(a.at)}<br /><span className="who">{a.actor}</span></span><span>{a.text}</span></li>
              ))}
            </ol>
          </section>
        </div>

        <aside className="side">
          <section className="panel">
            <div className="panel-h"><h2>Payment link</h2></div>
            <div className="panel-b">
              <div className="mono" style={{ wordBreak: "break-all", fontSize: 12 }}>{link}</div>
              <div style={{ display: "flex", gap: 8, flexWrap: "wrap" }}>
                <CopyButton text={link} label="Copy link" />
                <CopyButton text={instructions} label="Copy instructions" />
              </div>
              <dl className="kv" style={{ padding: 0, gridTemplateColumns: "96px 1fr" }}>
                <dt>Token</dt><dd>USDC <span className="faint mono">{r.tokenContract.slice(0, 6)}…{r.tokenContract.slice(-4)}</span></dd>
                <dt>Network</dt><dd>{CHAIN_NAMES[r.chain]}</dd>
                <dt>To</dt><dd className="mono" style={{ wordBreak: "break-all", fontSize: 12 }}>{r.receivingAddress}</dd>
                <dt>Created</dt><dd>{formatTime(r.createdAt)} by {r.createdBy}</dd>
              </dl>
            </div>
          </section>

          {reply && (
            <section className="panel">
              <div className="panel-h"><h2>Reply to the customer</h2><CopyButton text={reply} label="Copy reply" /></div>
              <div className="panel-b"><div className="reply">{reply}</div><span className="faint" style={{ fontSize: 12 }}>Built from this request&apos;s records only. Edit before sending if needed.</span></div>
            </section>
          )}

          <section className="panel">
            <div className="panel-h"><h2>Case</h2></div>
            <div className="panel-b"><OwnerAndNote requestId={r.id} owner={r.owner} /></div>
          </section>

          {r.demo && demo.scenarios.some((s) => s.id === r.id) && (
            <DemoControls scenarios={demo.scenarios} waitingForBlock={demo.waitingForBlock} inBlock={demo.inBlock} head={demo.head} compact only={r.id} />
          )}

          {v.state !== "completed" && (
            <section className="panel">
              <div className="panel-h"><h2>Record a real transaction</h2></div>
              <div className="panel-b"><AttachHash requestId={r.id} /></div>
            </section>
          )}
        </aside>
      </div>
    </div>
  );
}
